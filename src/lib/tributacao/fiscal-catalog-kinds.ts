export const fiscalCatalogKinds = ["EDIFICIO", "CONDOMINIO", "LOTEAMENTO", "LOCALIDADE", "ZONEAMENTO", "PGV", "SITUACAO_IMOVEL", "SITUACAO_EMPRESA", "TIPO_EMPRESA", "TIPO_SOCIO", "TIPO_VISTORIA_IMOVEL", "TIPO_VISTORIA_EMPRESA", "BCI_TERRENO", "BCI_UNIDADE", "BCI_RURAL", "FORMULARIO_EMPRESA", "FORMULARIO_ITBI"] as const;

export function fiscalCatalogEntityType(kind: typeof fiscalCatalogKinds[number]) {
  if (kind === "FORMULARIO_ITBI") return "ITBI_DECLARATION";
  if (["EDIFICIO", "CONDOMINIO", "LOTEAMENTO", "LOCALIDADE", "ZONEAMENTO", "PGV", "SITUACAO_IMOVEL", "TIPO_VISTORIA_IMOVEL", "BCI_TERRENO", "BCI_UNIDADE", "BCI_RURAL"].includes(kind)) return "REAL_ESTATE";
  return "ECONOMIC_REGISTRATION";
}
