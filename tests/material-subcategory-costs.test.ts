import assert from "node:assert/strict";
import test from "node:test";
import { readFile } from "node:fs/promises";
import { and, eq } from "drizzle-orm";
import { createPlanningExecutionFixture } from "./helpers/planning-execution-fixture";
import { createCommitment, createSettlement } from "../src/lib/financeiro";
import { createMunicipalCostObject, saveMunicipalCostItem, linkMunicipalCostItems, createMunicipalCostRule } from "../src/lib/financeiro/cost-catalog";
import { configureMunicipalCosts } from "../src/lib/financeiro/cost-ledger";
import { applyStockMovement } from "../src/lib/patrimonio/stock-service";
import { connectFinanceDrizzleFixture } from "./helpers/finance-drizzle-connection";
import { withDatabaseTransaction } from "../src/db/transaction";
import { users, userBudgetUnits } from "../src/db/schema/identity";
import { financialYears } from "../src/db/schema/finance-years";
import { budgetAppropriations } from "../src/db/schema/finance-budget";
import { planningExpenseNatures } from "../src/db/schema/planning-legal";
import { costCenters } from "../src/db/schema/master-data";
import { warehouses, materialCategories, materialSubcategories, materials, materialStocks } from "../src/db/schema/assets-stock";
import { municipalCostSources, municipalCostMovements } from "../src/db/schema/finance-costs";

test("P6: consumo congela subclasse canônica, seleciona regra e recusa classe/produto incompatíveis", async () => {
  const mode = process.env.CELERIFLOW_ACCOUNTING_MODE;
  process.env.CELERIFLOW_ACCOUNTING_MODE = "POC";
  const f = await createPlanningExecutionFixture(2026, 2, "EXECUTIVE", { expenseLineAmount: "600.00" });
  let transport: Awaited<ReturnType<typeof connectFinanceDrizzleFixture>> | undefined;
  try {
    transport = await connectFinanceDrizzleFixture(f.pg);
    const connection = transport.connection;
    const db = connection.db;
    await db.update(users).set({ ativo: true }).where(eq(users.id, "ana"));
    await f.pg.exec('ALTER TABLE "Material" DROP COLUMN "subcategoryId"; DROP TABLE "MaterialSubcategory";');
    await f.pg.exec(await readFile("prisma/migrations-ibema/20261014130000_material_subcategories/migration.sql", "utf8"));
    await db.update(financialYears).set({ status: "Aberto" }).where(eq(financialYears.id, "ano"));
    const [appropriation] = await db.select().from(budgetAppropriations).where(eq(budgetAppropriations.id, f.appropriationId)).limit(1);
    assert.ok(appropriation);
    await db.update(planningExpenseNatures).set({ code: "3.3.90.30" }).where(eq(planningExpenseNatures.id, appropriation.expenseNatureId));
    await db.insert(userBudgetUnits).values({ usuarioId: "ana", budgetUnitId: "ug" });
    await db.insert(costCenters).values({ id: "subclass-center", code: "SUBCLASS", name: "Centro de consumo", governmentEntityId: "ente", secretariatId: "secretaria" });
    await db.insert(warehouses).values({ id: "subclass-warehouse", name: "Almoxarifado", costCenterId: "subclass-center" });
    await db.insert(materialCategories).values([{ id: "class-1", code: "C1", name: "Classe 1" }, { id: "class-2", code: "C2", name: "Classe 2" }]);
    await db.insert(materialSubcategories).values({ id: "subclass-1", categoryId: "class-1", code: "S1", name: "Subclasse original" });
    await db.insert(materials).values({ id: "subclass-material", code: "MAT-SUB", name: "Material", categoryId: "class-1", subcategoryId: "subclass-1" });
    await db.insert(materialStocks).values({ warehouseId: "subclass-warehouse", materialId: "subclass-material", quantity: 10, unitCost: 2 });
    const date = new Date("2026-09-01T12:00:00Z");
    const reservation = await f.reserve("subclass-res", "20.00", date);
    const commitment = await createCommitment(connection, f.financeReviewer, { date, number: "SUBCLASS-EMP", value: "20.00", type: "Ordinário", history: "Aquisição de material", appropriationId: f.appropriationId, supplierId: "fornecedor", reservationId: reservation.id });
    const settlement = await createSettlement(connection, f.financeReviewer, { date, value: "20.00", commitmentId: commitment.id, documentId: "documento-fiscal", documentRef: "Material recebido", authorId: "servidora-ana" });
    const object = await createMunicipalCostObject(connection, f.actor, { financialYearId: "ano", budgetUnitId: "ug", description: "Serviços", detailedDescription: "Serviços municipais" });
    const costActor = { ...f.actor, allowedBudgetUnitIds: ["ug", "ug-restrita"] };
    const item = await saveMunicipalCostItem(connection, costActor, { financialYearId: "ano", identifier: "MATERIAL-SUB", description: "Material", detailedDescription: "Material por subclasse", identificationClass: "TEXTO", behavior: "VARIABLE", isActive: true });
    await linkMunicipalCostItems(connection, f.actor, { objectIds: [object.id], itemIds: [item.id] });
    const rule = { financialYearId: "ano", budgetUnitId: "ug", title: "Consumo por subclasse", sourceType: "STOCK_CONSUMPTION" as const, selector: { subcategoryId: "subclass-1" }, shares: [{ objectId: object.id, itemId: item.id, percentage: "100" }], priority: 1, effectiveFrom: new Date("2026-01-01") };
    await assert.rejects(createMunicipalCostRule(connection, f.actor, { ...rule, selector: { subcategoryId: "subclass-1", categoryId: "class-2" } }), /Subclasse/);
    await assert.rejects(createMunicipalCostRule(connection, f.actor, { ...rule, selector: { materialId: "subclass-material", categoryId: "class-2" } }), /Produto/);
    await createMunicipalCostRule(connection, f.actor, rule);
    await configureMunicipalCosts(connection, costActor, { financialYearId: "ano", enabled: true, sourceTypes: ["STOCK_CONSUMPTION"], effectiveFrom: new Date("2026-01-01"), reason: "Apropriação de consumo por subclasse" });
    const result = await withDatabaseTransaction(connection, tx => applyStockMovement(tx, { kind: "EXIT", warehouseId: "subclass-warehouse", materialId: "subclass-material", quantity: 2, settlementId: settlement.id, reason: "CONSUMO_ORCAMENTARIO:Consumo municipal", actor: f.actor }));
    const [source] = await db.select().from(municipalCostSources).where(and(eq(municipalCostSources.sourceType, "STOCK_CONSUMPTION"), eq(municipalCostSources.sourceId, result.movement.id))).limit(1);
    assert.ok(source);
    const movements = await db.select().from(municipalCostMovements).where(eq(municipalCostMovements.sourceId, source.id));
    assert.equal(source.amount.toFixed(2), "4.00");
    assert.equal(movements.length, 1);
    const memory = source.snapshot;
    assert.ok(memory && typeof memory === "object" && !Array.isArray(memory));
    const dimensions = memory.dimensions, evidence = memory.evidence;
    assert.ok(dimensions && typeof dimensions === "object" && !Array.isArray(dimensions));
    assert.ok(evidence && typeof evidence === "object" && !Array.isArray(evidence));
    const subcategory = evidence.materialSubcategory;
    assert.ok(subcategory && typeof subcategory === "object" && !Array.isArray(subcategory));
    assert.equal(dimensions.subcategoryId, "subclass-1");
    assert.equal(subcategory.name, "Subclasse original");
    await db.update(materialSubcategories).set({ name: "Nome atual", isActive: false }).where(eq(materialSubcategories.id, "subclass-1"));
    const [frozen] = await db.select().from(municipalCostSources).where(eq(municipalCostSources.id, source.id)).limit(1);
    assert.ok(frozen);
    assert.deepEqual(frozen.snapshot, source.snapshot);
    await assert.rejects(createMunicipalCostRule(connection, f.actor, rule), /Subclasse/);
  } finally {
    try { await transport?.close(); } finally { await f.close(); }
    if (mode === undefined) delete process.env.CELERIFLOW_ACCOUNTING_MODE; else process.env.CELERIFLOW_ACCOUNTING_MODE = mode;
  }
});
