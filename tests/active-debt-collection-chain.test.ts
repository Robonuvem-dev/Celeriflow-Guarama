import assert from "node:assert/strict";
import test from "node:test";
import { createPlanningExecutionFixture } from "./helpers/planning-execution-fixture";
import { configureTaxFinancialMapping, createTaxAssessment, enrollAssessmentInActiveDebt, generateTaxGuide } from "../src/lib/tributacao";
import { daBook, enrollManualDebt, issueDaGuide, listEnrollmentCandidates, resolveProtestItem, selectProtestCandidates, settleDebtByGuide, writeOffDebt } from "../src/lib/tributacao/s9-service";
import { reverseTaxPayment } from "../src/lib/tributacao/payment-reversal";

for (const jurisdiction of ["EXECUTIVE", "LEGISLATIVE"] as const) {
  test(`P2: dívida/guia/arrecadação parcial, replay, estorno e rollback (${jurisdiction})`, async () => {
    const mode = process.env.CELERIFLOW_ACCOUNTING_MODE;
    process.env.CELERIFLOW_ACCOUNTING_MODE = "POC";
    const f = await createPlanningExecutionFixture(2026, 2, jurisdiction);
    try {
      await f.db.financialYear.update({ where: { id: "ano" }, data: { status: "Aberto" } });
      await f.db.tax.create({ data: { id: "tax-debt", name: "IPTU municipal", taxType: "Imposto", isActive: true } });
      await f.db.taxpayer.create({ data: { id: "debt-payer", taxpayerType: "PJ", companyId: "empresa", status: "Ativo" } });
      await configureTaxFinancialMapping(f.db, f.actor, { taxId: "tax-debt", revenueNatureId: "receita", resourceSourceId: "livre", defaultBankAccountId: "banco" });
      const base = { year: 2026, taxId: "tax-debt", taxpayerId: "debt-payer", taxableBase: "100", rate: "100", competence: new Date("2026-01-01T12:00:00Z") };
      const assessment = await createTaxAssessment(f.db, f.actor, base);
      const debt = await enrollAssessmentInActiveDebt(f.db, f.actor, assessment.id);
      await f.db.activeDebt.update({ where: { id: debt.id }, data: { status: "INSCRITA", cdaNumber: "CDA-2026-001" } });
      assert.equal((await daBook(f.db, undefined, ["ug"])).length, 1);
      assert.equal((await daBook(f.db, undefined, [])).length, 0);
      assert.equal((await listEnrollmentCandidates(f.db, [])).length, 0);
      assert.equal((await selectProtestCandidates(f.db, [])).length, 0);
      const guide = await generateTaxGuide(f.db, f.actor, { assessmentId: assessment.id, dueDate: new Date("2026-12-31") });
      const unrelated = await createTaxAssessment(f.db, f.actor, base);
      const otherGuide = await generateTaxGuide(f.db, f.actor, { assessmentId: unrelated.id, dueDate: new Date("2026-12-31") });
      const input = { debtId: debt.id, guideId: guide.id, amount: 25, paymentMethod: "Manual", idempotencyKey: "debt-payment-a" };
      await assert.rejects(settleDebtByGuide(f.db, f.actor, { ...input, guideId: otherGuide.id }), /não pertence/);
      await assert.rejects(settleDebtByGuide(f.db, { ...f.actor, allowedBudgetUnitIds: [] }, input), /autorizadas/);
      assert.equal(await f.db.taxPayment.count(), 0);
      await f.pg.exec(`CREATE FUNCTION fail_debt_event() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN IF NEW."eventType"='PAGAMENTO' THEN RAISE EXCEPTION 'debt chain rollback'; END IF; RETURN NEW; END $$; CREATE TRIGGER fail_debt_event BEFORE INSERT ON "TaxActiveDebtEvent" FOR EACH ROW EXECUTE FUNCTION fail_debt_event();`);
      await assert.rejects(settleDebtByGuide(f.db, f.actor, input), /debt chain rollback/);
      assert.equal(await f.db.taxPayment.count(), 0);
      assert.equal(await f.db.revenue.count(), 0);
      assert.equal((await f.db.activeDebt.findUniqueOrThrow({ where: { id: debt.id } })).updatedValueDecimal!.toFixed(2), "100.00");
      await f.pg.exec('DROP TRIGGER fail_debt_event ON "TaxActiveDebtEvent"; DROP FUNCTION fail_debt_event();');
      const results = await Promise.all([settleDebtByGuide(f.db, f.actor, input), settleDebtByGuide(f.db, f.actor, input)]);
      assert.equal(results[0].updatedValueDecimal!.toFixed(2), "75.00");
      assert.equal(results[1].updatedValueDecimal!.toFixed(2), "75.00");
      assert.equal(await f.db.taxPayment.count(), 1);
      assert.equal(await f.db.taxActiveDebtEvent.count({ where: { activeDebtId: debt.id, eventType: "PAGAMENTO" } }), 1);
      await assert.rejects(settleDebtByGuide(f.db, f.actor, { ...input, amount: 30 }), /outros dados/);
      await settleDebtByGuide(f.db, f.actor, { ...input, amount: 75, idempotencyKey: "debt-payment-b" });
      const settled = await f.db.activeDebt.findUniqueOrThrow({ where: { id: debt.id } });
      assert.equal(settled.status, "PAGA");
      assert.equal(settled.updatedValueDecimal!.toFixed(2), "0.00");
      const payment = await f.db.taxPayment.findUniqueOrThrow({ where: { idempotencyKey: input.idempotencyKey } });
      await reverseTaxPayment(f.db, f.actor, { paymentId: payment.id, date: new Date(), reason: "Estorno fundamentado da arrecadação da dívida", idempotencyKey: "debt-payment-reversal" });
      const reopened = await f.db.activeDebt.findUniqueOrThrow({ where: { id: debt.id } });
      assert.equal(reopened.status, "EM_COBRANCA");
      assert.equal(reopened.updatedValueDecimal!.toFixed(2), "25.00");
      const batch = await f.db.taxProtestBatch.create({ data: { batchNumber: "PROT-2026-001", fileContent: {}, createdByUsuarioId: "ana" } });
      const item = await f.db.taxProtestItem.create({ data: { batchId: batch.id, activeDebtId: debt.id, status: "EM_ACOMPANHAMENTO" } });
      await assert.rejects(resolveProtestItem(f.db, f.actor, { itemId: item.id, action: "BAIXAR_PAGAMENTO", reason: "Baixa com saldo ainda pendente" }), /Receba ou compense/);
      assert.equal((await f.db.taxProtestItem.findUniqueOrThrow({ where: { id: item.id } })).status, "EM_ACOMPANHAMENTO");
      assert.equal((await f.db.activeDebt.findUniqueOrThrow({ where: { id: debt.id } })).updatedValueDecimal!.toFixed(2), "25.00");
      const extinctionAssessment = await createTaxAssessment(f.db, f.actor, base);
      const extinctionDebt = await enrollAssessmentInActiveDebt(f.db, f.actor, extinctionAssessment.id);
      await f.db.activeDebt.update({ where: { id: extinctionDebt.id }, data: { status: "INSCRITA" } });
      const extinction = { debtId: extinctionDebt.id, reason: "Extinção administrativa fundamentada do débito" };
      await f.pg.exec(`CREATE FUNCTION fail_debt_extinction() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN IF NEW.source='DIVIDA_ATIVA' THEN RAISE EXCEPTION 'debt extinction rollback'; END IF; RETURN NEW; END $$; CREATE TRIGGER fail_debt_extinction BEFORE INSERT ON "TaxRegistryEntry" FOR EACH ROW EXECUTE FUNCTION fail_debt_extinction();`);
      await assert.rejects(writeOffDebt(f.db, f.actor, extinction), /debt extinction rollback/);
      assert.equal((await f.db.taxAssessment.findUniqueOrThrow({ where: { id: extinctionAssessment.id } })).finalValueDecimal!.toFixed(2), "100.00");
      assert.equal((await f.db.activeDebt.findUniqueOrThrow({ where: { id: extinctionDebt.id } })).status, "INSCRITA");
      await f.pg.exec('DROP TRIGGER fail_debt_extinction ON "TaxRegistryEntry"; DROP FUNCTION fail_debt_extinction();');
      const writtenOff = await writeOffDebt(f.db, f.actor, extinction);
      assert.equal(writtenOff.status, "BAIXADA");
      assert.equal(writtenOff.updatedValueDecimal!.toFixed(2), "0.00");
      assert.equal((await f.db.taxAssessment.findUniqueOrThrow({ where: { id: extinctionAssessment.id } })).finalValueDecimal!.toFixed(2), "0.00");
      assert.equal((await writeOffDebt(f.db, f.actor, extinction)).id, writtenOff.id);
      await assert.rejects(writeOffDebt(f.db, f.actor, { ...extinction, reason: "Outro fundamento administrativo" }), /outros dados/);
      const manualInput = { taxpayerId: "debt-payer", originDebtType: "IPTU municipal", year: 2020, value: 50, sourceKey: "historical-manual", budgetUnitId: "ug" };
      const manual = await Promise.all([enrollManualDebt(f.db, f.actor, manualInput), enrollManualDebt(f.db, f.actor, manualInput)]);
      assert.equal(manual[0].debt.id, manual[1].debt.id);
      assert.equal(manual.filter(result => result.created).length, 1);
      assert.equal(manual[0].debt.budgetUnitId, "ug");
      await assert.rejects(enrollManualDebt(f.db, f.actor, { ...manualInput, value: 51 }), /outros dados/);
      await f.db.activeDebt.update({ where: { id: manual[0].debt.id }, data: { status: "INSCRITA", cdaNumber: "CDA-2020-001" } });
      const manualGuideInput = { debtId: manual[0].debt.id, dueDate: new Date("2026-12-20") };
      const manualGuides = await Promise.all([issueDaGuide(f.db, f.actor, manualGuideInput), issueDaGuide(f.db, f.actor, manualGuideInput)]);
      assert.equal(manualGuides[0].id, manualGuides[1].id);
      const legacyAssessment = await f.db.taxAssessment.findUniqueOrThrow({ where: { id: manualGuides[0].assessmentId } });
      assert.equal(legacyAssessment.year, 2020);
      assert.equal(await f.db.taxRegistryEntry.count({ where: { entityId: legacyAssessment.id, category: "ACCOUNTING_POSITION" } }), 0);
      const historicalCollection = await settleDebtByGuide(f.db, f.actor, { debtId: manual[0].debt.id, guideId: manualGuides[0].id, amount: 50, paymentMethod: "Manual", idempotencyKey: "historical-debt-collection" });
      assert.equal(historicalCollection.status, "PAGA");
      assert.equal((await f.db.revenue.findFirstOrThrow({ where: { history: { contains: manualGuides[0].guideNumber! } } })).financialYearId, "ano");
    } finally {
      if (mode === undefined) delete process.env.CELERIFLOW_ACCOUNTING_MODE;
      else process.env.CELERIFLOW_ACCOUNTING_MODE = mode;
      await f.close();
    }
  });
}
