import { createHash } from "node:crypto";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { spawnSync } from "node:child_process";
import ts from "typescript";

// Each source and each Next route validation is checked in one partition, with
// all of its imports checked normally. No compiler strictness is disabled.
// Separate processes release Prisma's large instantiated type graph between
// partitions, keeping the production heap at 6 GB even on a cold build.
const root = process.cwd();
const configPath = join(root, "tsconfig.build.json");
const config = ts.readConfigFile(configPath, ts.sys.readFile);
if (config.error) throw new Error(ts.flattenDiagnosticMessageText(config.error.messageText, "\n"));
const parsed = ts.parseJsonConfigFileContent(config.config, ts.sys, root);
if (parsed.errors.length) throw new Error(ts.formatDiagnosticsWithColorAndContext(parsed.errors, { getCanonicalFileName: file => file, getCurrentDirectory: () => root, getNewLine: () => "\n" }));
const count = 4;
const cold = process.argv.includes("--cold");
const partition = file => {
  const parts = relative(root, file).replaceAll("\\", "/").split("/");
  // Keep one domain's pages/actions/libraries together where possible.
  const key = parts[1] === "lib" ? parts[2] : parts[1] === "app" && parts[2] === "app-domain" ? parts[3] : parts.slice(0, 3).join("/");
  return createHash("sha256").update(key || file).digest().readUInt32BE(0) % count;
};
const groups = Array.from({ length: count }, () => []);
const validatorPath = join(root, ".next", "types", "validator.ts");
if (!existsSync(validatorPath)) throw new Error("Execute next typegen antes da checagem.");
const shared = [];
for (const file of parsed.fileNames) {
  const name = relative(root, file).replaceAll("\\", "/");
  if (resolve(file) === resolve(validatorPath) || /^\.next\/types\/typecheck-part-\d+\.ts$/.test(name)) continue;
  if (name.startsWith("src/") && !file.endsWith(".d.ts")) groups[partition(file)].push(file);
  else shared.push(file);
}
const source = ts.createSourceFile(validatorPath, readFileSync(validatorPath, "utf8"), ts.ScriptTarget.Latest, true);
const preamble = source.statements.filter(statement => !ts.isBlock(statement)).map(statement => statement.getFullText(source)).join("\n");
const validations = Array.from({ length: count }, () => []);
for (const statement of source.statements.filter(ts.isBlock)) {
  let moduleName;
  const visit = node => {
    if (ts.isImportTypeNode(node) && ts.isLiteralTypeNode(node.argument) && ts.isStringLiteral(node.argument.literal)) moduleName = node.argument.literal.text;
    ts.forEachChild(node, visit);
  };
  visit(statement);
  if (!moduleName) throw new Error("Validação Next sem import de rota; formato não reconhecido.");
  const resolvedRoute = ts.resolveModuleName(moduleName, validatorPath, parsed.options, ts.sys).resolvedModule;
  if (!resolvedRoute) throw new Error(`Rota Next não resolvida: ${moduleName}`);
  validations[partition(resolvedRoute.resolvedFileName)].push(statement.getFullText(source));
}
const directory = join(root, ".next", "cache", "typecheck-partitions");
mkdirSync(directory, { recursive: true });
for (let index = 0; index < count; index++) {
  const validator = join(dirname(validatorPath), `typecheck-part-${index}.ts`);
  writeFileSync(validator, `// Generated by typecheck-build.mjs; do not edit.\n${preamble}\n${validations[index].join("\n")}\n`);
  const project = join(directory, `part-${index}.json`);
  writeFileSync(project, JSON.stringify({ extends: configPath, compilerOptions: { incremental: !cold, tsBuildInfoFile: join(directory, `part-${index}.tsbuildinfo`) }, files: [...shared, ...groups[index], validator], include: [], exclude: [] }, null, 2));
  console.log(`[typecheck] Partition ${index + 1}/${count}: ${groups[index].length} sources, ${validations[index].length} route validations`);
  const result = spawnSync(process.execPath, [join(root, "node_modules", "typescript", "bin", "tsc"), "--project", project, "--noEmit", "--extendedDiagnostics"], { stdio: "inherit", env: process.env });
  if (result.error) throw result.error;
  if (result.status !== 0) process.exit(result.status ?? 1);
}
